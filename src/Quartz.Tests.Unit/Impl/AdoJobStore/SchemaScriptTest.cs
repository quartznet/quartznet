    /// <summary>
    /// The dialect whose model a fresh-install script is held to: its own, or SQL Server's for the two
    /// SQL Server variants.
    /// </summary>
    internal static string Counterpart(string script) => script.StartsWith("sqlServer", StringComparison.Ordinal) ? "sqlServer" : script;

    private static bool Exempt(string script, string table) => Exemptions.ContainsKey((script, table));

    private static SqlObjects Generated(string script) => SqlObjects.Parse(GeneratedScript(Counterpart(script)), Counterpart(script));

    private static SqlObjects FreshInstall(string script) => SqlObjects.Parse(FreshInstallScript(script), Counterpart(script));

    internal static string GeneratedScript(string dialect)
    {
        string name = $"Quartz.Impl.AdoJobStore.Schema.create_{dialect}.sql";

        using Stream stream = typeof(IScheduler).Assembly.GetManifestResourceStream(name)
            ?? throw new InvalidOperationException(
                $"'{name}' is not embedded in Quartz.dll. Run 'dotnet fallout GenerateSchema'.");

        using StreamReader reader = new(stream, Encoding.UTF8);
        return reader.ReadToEnd();
    }

    private static string FreshInstallScript(string script)
    {
        string path = Path.Combine(RepositoryRoot.Find().FullName, "database", "tables", $"tables_{script}.sql");
        return File.ReadAllText(path);
    }

    private static string[] Lines(string script) => script.Replace("\r\n", "\n").Split('\n');

    private static string[] Chunks(string script) =>
        script.Replace("\r\n", "\n").Split($"\n{StatementSeparator}\n");

    private static IEnumerable<string> Statements(string script) => Chunks(script).Where(HasStatement);

    /// <summary>Whether a chunk holds anything but blank lines and whole-line comments.</summary>
    private static bool HasStatement(string chunk) =>
        Lines(chunk).Any(line => line.Trim().Length > 0 && !line.TrimStart().StartsWith("--", StringComparison.Ordinal));
}
